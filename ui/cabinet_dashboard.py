"""Native dashboard layout; actions and worker ownership live in CabinetWindow."""
from PyQt6 import QtCore, QtWidgets
from ui.theme import apply_dashboard_theme, label
from ui.window_chrome import WindowChrome


class DashboardLayout:
    def build_dashboard(self):
        self.setWindowTitle('MangaFlow — личный кабинет')
        self.setWindowFlag(QtCore.Qt.WindowType.FramelessWindowHint, True)
        self.resize(1240, 820)
        self.setMinimumSize(1040, 690)
        apply_dashboard_theme(self)
        root = QtWidgets.QWidget()
        self.setCentralWidget(root)
        shell = QtWidgets.QHBoxLayout(root)
        shell.setContentsMargins(12, 12, 12, 12)
        shell.setSpacing(12)

        sidebar = QtWidgets.QFrame()
        sidebar.setObjectName('sidebar')
        sidebar.setFixedWidth(185)
        navigation = QtWidgets.QVBoxLayout(sidebar)
        navigation.setContentsMargins(16, 24, 16, 20)
        navigation.setSpacing(12)
        navigation.addWidget(label('MF /', 'brand'))
        navigation.addWidget(label('M A N G A F L O W', 'eyebrow'))
        navigation.addSpacing(24)
        self.nav_group = QtWidgets.QButtonGroup(self)
        self.nav_group.setExclusive(True)
        for index, (text, icon) in enumerate([
                ('Пакетный перевод', QtWidgets.QStyle.StandardPixmap.SP_FileDialogContentsView),
                ('История', QtWidgets.QStyle.StandardPixmap.SP_FileDialogDetailedView),
                ('Профиль', QtWidgets.QStyle.StandardPixmap.SP_ComputerIcon)]):
            button = QtWidgets.QPushButton(text)
            button.setObjectName('nav')
            button.setCheckable(True)
            button.setIcon(self.style().standardIcon(icon))
            self.nav_group.addButton(button, index)
            navigation.addWidget(button)
            if index == 0:
                button.setChecked(True)
        self.nav_group.idClicked.connect(self.navigate)
        navigation.addStretch()
        navigation.addWidget(label('ЛОКАЛЬНЫЙ ПЕРЕВОД\nManga-OCR · Ollama', 'muted'))
        shell.addWidget(sidebar)

        content = QtWidgets.QVBoxLayout()
        content.setSpacing(16)
        shell.addLayout(content, 1)
        header = QtWidgets.QWidget()
        top = QtWidgets.QHBoxLayout(header)
        top.setContentsMargins(0, 0, 0, 0)
        top.addWidget(label('Личный кабинет', 'section'))
        top.addStretch()
        activated = label(f"● Activated   /   {self.user['login']}   /   {self.user['invite']}", 'activated')
        activated.setTextFormat(QtCore.Qt.TextFormat.PlainText)
        top.addWidget(activated)
        for text, callback in [('—', self.showMinimized), ('□', self.toggle_maximized), ('×', self.close)]:
            control = QtWidgets.QPushButton(text)
            control.setObjectName('windowControl')
            control.setFixedSize(30, 30)
            control.clicked.connect(callback)
            top.addWidget(control)
        content.addWidget(header)
        self.window_chrome = WindowChrome(self, header)
        columns = QtWidgets.QHBoxLayout()
        columns.setSpacing(16)
        content.addLayout(columns, 1)
        self.pages = QtWidgets.QStackedWidget()
        columns.addWidget(self.pages, 3)

        batch = QtWidgets.QFrame()
        batch.setObjectName('panel')
        form = QtWidgets.QVBoxLayout(batch)
        form.setContentsMargins(24, 24, 24, 24)
        form.setSpacing(16)
        form.addWidget(label('Пакетный перевод', 'heading'))
        description = label('Загрузите страницы манги — перевод останется\nвнутри оригинальных облачков.', 'muted')
        description.setWordWrap(True)
        form.addWidget(description)
        form.addSpacing(12)
        form.addWidget(label('НАЗВАНИЕ ТОМА / ПРОЕКТА', 'eyebrow'))
        self.title = QtWidgets.QLineEdit()
        self.title.setPlaceholderText('Например, Том 01 — Начало')
        form.addWidget(self.title)
        picks = QtWidgets.QHBoxLayout()
        self.files_button = QtWidgets.QPushButton('Выбрать изображения')
        self.folder_button = QtWidgets.QPushButton('Выбрать папку')
        self.files_button.clicked.connect(self.pick_files)
        self.folder_button.clicked.connect(self.pick_folder)
        picks.addWidget(self.files_button)
        picks.addWidget(self.folder_button)
        form.addLayout(picks)
        self.selection = label('Страницы не выбраны', 'muted')
        form.addWidget(self.selection)
        self.start = QtWidgets.QPushButton('Запустить перевод  →')
        self.start.setObjectName('primary')
        self.start.clicked.connect(self.start_batch)
        form.addWidget(self.start)
        self.progress = QtWidgets.QProgressBar()
        self.progress.setValue(0)
        self.progress.setTextVisible(False)
        form.addWidget(self.progress)
        self.status = label('Готов к работе', 'status')
        self.status.setWordWrap(True)
        self.status.setTextFormat(QtCore.Qt.TextFormat.PlainText)
        form.addWidget(self.status)
        form.addWidget(label('ЖУРНАЛ ОБРАБОТКИ', 'eyebrow'))
        self.log = QtWidgets.QPlainTextEdit()
        self.log.setReadOnly(True)
        self.log.setMaximumBlockCount(500)
        form.addWidget(self.log, 1)
        self.pages.addWidget(batch)

        history_page = QtWidgets.QFrame()
        history_page.setObjectName('panel')
        history_layout = QtWidgets.QVBoxLayout(history_page)
        history_layout.setContentsMargins(24, 24, 24, 24)
        history_layout.addWidget(label('История переводов', 'heading'))
        self.history_details = QtWidgets.QPlainTextEdit()
        self.history_details.setReadOnly(True)
        self.history_details.setPlaceholderText('Выберите том в списке справа, чтобы посмотреть детали и ошибки.')
        history_layout.addWidget(self.history_details, 1)
        self.pages.addWidget(history_page)

        profile = QtWidgets.QFrame()
        profile.setObjectName('panel')
        profile_layout = QtWidgets.QVBoxLayout(profile)
        profile_layout.setContentsMargins(24, 24, 24, 24)
        profile_layout.addWidget(label('Профиль', 'heading'))
        for caption, value in [('Логин', self.user['login']), ('Инвайт', self.user['invite']),
                               ('HWID', self.user['hwid'][:16] + '…'), ('Доступ', 'Activated')]:
            profile_layout.addWidget(label(caption.upper(), 'eyebrow'))
            field = QtWidgets.QLineEdit(str(value))
            field.setReadOnly(True)
            profile_layout.addWidget(field)
        profile_layout.addStretch()
        self.pages.addWidget(profile)

        right = QtWidgets.QFrame()
        right.setObjectName('panel')
        right.setMinimumWidth(350)
        summary = QtWidgets.QVBoxLayout(right)
        summary.setContentsMargins(18, 24, 18, 20)
        summary.setSpacing(14)
        summary.addWidget(label('Ваша активность', 'section'))
        cards = QtWidgets.QHBoxLayout()
        self.stats_labels = []
        for title in ['Томов готово', 'Страниц готово']:
            card = QtWidgets.QGroupBox(title)
            card_layout = QtWidgets.QVBoxLayout(card)
            number = label('0', 'statNumber')
            self.stats_labels.append(number)
            card_layout.addWidget(number)
            cards.addWidget(card)
        summary.addLayout(cards)
        self.summary_status = label('Статус: готов', 'status')
        summary.addWidget(self.summary_status)
        summary.addWidget(label('Последние переводы', 'section'))
        self.table = QtWidgets.QTableWidget(0, 4)
        self.table.setHorizontalHeaderLabels(['Том', 'Дата UTC', 'Стр.', 'Статус'])
        self.table.setSelectionBehavior(QtWidgets.QAbstractItemView.SelectionBehavior.SelectRows)
        self.table.setSelectionMode(QtWidgets.QAbstractItemView.SelectionMode.SingleSelection)
        self.table.setEditTriggers(QtWidgets.QAbstractItemView.EditTrigger.NoEditTriggers)
        self.table.verticalHeader().setVisible(False)
        self.table.verticalHeader().setDefaultSectionSize(46)
        self.table.horizontalHeader().setSectionResizeMode(QtWidgets.QHeaderView.ResizeMode.ResizeToContents)
        self.table.horizontalHeader().setSectionResizeMode(0, QtWidgets.QHeaderView.ResizeMode.Stretch)
        self.table.itemSelectionChanged.connect(self.update_history_details)
        summary.addWidget(self.table, 1)
        for text, action in [('Скачать ZIP', self.save_zip), ('Открыть папку', self.open_folder)]:
            button = QtWidgets.QPushButton(text)
            button.clicked.connect(action)
            summary.addWidget(button)
        bottom = QtWidgets.QHBoxLayout()
        for text, action in [('Удалить', self.delete_record), ('Обновить', self.refresh)]:
            button = QtWidgets.QPushButton(text)
            if text == 'Удалить':
                button.setObjectName('danger')
            button.clicked.connect(action)
            bottom.addWidget(button)
        summary.addLayout(bottom)
        summary.addWidget(QtWidgets.QSizeGrip(self), 0, QtCore.Qt.AlignmentFlag.AlignRight)
        columns.addWidget(right, 2)

    def toggle_maximized(self):
        self.showNormal() if self.isMaximized() else self.showMaximized()

    def navigate(self, index):
        self.pages.setCurrentIndex(index)
        if index == 1:
            self.refresh()
            self.update_history_details()

    def update_history_details(self):
        row = self.selected()
        if row is None:
            self.history_details.clear()
            return
        try:
            pages = self.store.pages(row['id'])
            lines = [row['title'], f"Дата UTC: {row['created_at']}", f"Статус: {row['status']}", row['error'] or '', '']
            lines.extend(f"{p['filename']} — {p['status']}" + (f"\n  {p['error']}" if p['error'] else '') for p in pages)
            self.history_details.setPlainText('\n'.join(lines))
        except Exception as exc:
            self.report_error(exc)
